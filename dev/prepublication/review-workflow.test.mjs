import {strict as assert} from "node:assert";
import {findMatches,confirmMatch,approvePublication,preparePublish} from "./review-workflow.mjs";
const current={projectId:"abc",meta:{brand:"Brand A",client:"Client"},media:[{src:"https://example.test/a.jpg"}]};
const candidate={projectId:"abc",meta:{brand:"Brand A"},status:"ready_for_review",media:[{src:"https://example.test/a.jpg"},{src:"https://example.test/b.jpg"}]};
const galleries=[{galleryId:"pre-publication",meta:{visible:false},tiles:[candidate]},{galleryId:"stores",meta:{visible:true},tiles:[current]}];
const matches=findMatches(candidate,galleries);
assert.equal(matches.length,1);
assert.equal(matches[0].score,100);
assert.equal(matches[0].galleryId,"stores");
assert.throws(()=>preparePublish(candidate,galleries),/approval/);
const linked=confirmMatch(candidate,matches[0],"owner");
assert.equal(linked.status,"match_approved");
assert.throws(()=>preparePublish(linked,galleries),/approval/);
const approved=approvePublication(linked,"owner");
const plan=preparePublish(approved,galleries);
assert.equal(plan.addedMediaCount,1);
assert.equal(plan.nextGalleries[1].tiles[0].media.length,2);
assert.equal(galleries[1].tiles[0].media.length,1);
assert.equal(plan.nextGalleries[0].meta.visible,false);
assert.equal(findMatches({meta:{brand:"Unknown"},media:[]},galleries).length,0);
assert.throws(()=>confirmMatch(candidate,{galleryId:"stores",tileIndex:0},""),/reviewer/);
console.log("PASS: match, duplicate filtering, two approvals, immutable plan, staging isolation");
